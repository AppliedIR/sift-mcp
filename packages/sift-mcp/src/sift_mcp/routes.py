"""The shell commands that have an MCP route: `mcp-routes.tsv`.

Each line names an executable (by its basename) and the MCP tool that runs
it with the case audit: every forensic tool in the catalog goes through
sift-mcp's `run_command`, and `vhir ingest` through opensearch-mcp's
`idx_ingest`. The catalog's general-purpose utilities (its `analysis`
category: grep, ls, sed and the like) have no route. The audit hooks read the
file to mark a routed shell command and advise the MCP tool; they never block
it. The rendered file is committed beside the hooks; a test renders it again
and compares, so a catalog change can't reach the hooks unreviewed.

Regenerate with: ``python -m sift_mcp.routes <sift-mcp>/claude-code/shared/hooks``
"""

from __future__ import annotations

import sys
from pathlib import Path

from sift_mcp.catalog import load_catalog

FILENAME = "mcp-routes.tsv"
UNROUTED_CATEGORIES = {"analysis"}
EXTRA = [("vhir ingest", "opensearch-mcp idx_ingest", "")]


def render() -> str:
    rows = {
        td.binary: ("sift-mcp run_command", td.name)
        for td in load_catalog().values()
        if td.category not in UNROUTED_CATEGORIES
    }
    for command, route, tool in EXTRA:
        rows[command] = (route, tool)
    lines = [
        "# Shell commands with an MCP route: command, route, catalog tool.",
        "# Generated by sift_mcp.routes from the catalog; don't edit by hand.",
    ]
    lines += [
        f"{c}\t{r}\t{t}"
        for c, (r, t) in sorted(rows.items(), key=lambda x: x[0].lower())
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: python -m sift_mcp.routes <sift-mcp>/claude-code/shared/hooks")
    out = Path(sys.argv[1]) / FILENAME
    out.write_text(render(), encoding="utf-8")
    print(out)
